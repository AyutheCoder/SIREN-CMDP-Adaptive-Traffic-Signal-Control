def esc(s: str) -> str:
    return s.replace("_", r"\_")


def fmt(agg: dict, key: str, places: int = 2, with_ci: bool = True) -> str:
    mean = agg.get(f"{key}_mean")
    if mean is None or not np.isfinite(mean):
        return "--"
    if not with_ci:
        return f"{mean:.{places}f}"
    ci = agg.get(f"{key}_ci95", 0.0)
    return f"{mean:.{places}f}\\,$\\pm$\\,{ci:.{places}f}"


def fmt_median(agg: dict) -> str:
    """Median delay -- read this before the mean, given the heavy tail."""
    v = agg.get("mean_time_loss_s_median")
    return f"{v:.2f}" if v is not None and np.isfinite(v) else "--"


def fmt_jam(agg: dict) -> str:
    """Seeds that gridlocked. A bare aggregate, not a per-run mean."""
    n = agg.get("n_jammed")
    total = agg.get("n_runs")
    if n is None or total is None:
        return "--"
    return f"{int(n)}/{int(total)}"


def _sorted_names(results: dict):
    known = [n for n in ORDER if n in results]
    extra = sorted(n for n in results if n not in ORDER)
    return known + extra


