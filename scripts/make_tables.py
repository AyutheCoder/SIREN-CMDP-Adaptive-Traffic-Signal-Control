def _md(agg: dict, key: str, places: int = 2) -> str:
    v = agg.get(f"{key}_mean")
    if v is None or not math.isfinite(v):
        return "--"
    return f"{v:.{places}f}"


def readme_results(data: dict) -> str:
    """The markdown table the README quotes, generated from the same JSON.

    The README is the first thing anyone reads and the easiest thing to let go
    stale. Generating its table from the evaluation output means a number in the
    README is a number the code produced, on the same terms as every table in
    the paper.
    """
    results = data.get("results", {})
    cfg = data.get("config", {})
    rows = [(k, lbl) for k, lbl in README_ROWS if k in results]
    if not rows:
        return "<!-- no evaluation data -->\n"
    out = [
        f"<!-- Generated by scripts/make_tables.py from "
        f"results/evaluation_{cfg.get('regime', 'balanced')}.json. Do not edit. -->",
        "",
        "| controller | median (s) | mean (s) | jam | EV stopped (s) | EV stops | clean pass |",
        "|---|---|---|---|---|---|---|",
    ]
    for key, label in rows:
        agg = results[key]["aggregate"]
        med = agg.get("mean_time_loss_s_median", float("nan"))
        jam = f"{agg.get('n_jammed', 0):.0f}/{agg.get('n_runs', 0):.0f}"
        out.append(
            f"| {label} | {med:.2f} | {_md(agg, 'mean_time_loss_s')} | {jam} | "
            f"{_md(agg, 'ev_mean_waiting_time_s')} | "
            f"{_md(agg, 'ev_mean_stops')} | "
            f"{_md(agg, 'ev_zero_stop_rate', 3)} |")
    out.append("")
    return "\n".join(out) + "\n"


def readme_sensing(bench: dict) -> str:
    """The sensing comparison, in the README's markdown."""
    modes = bench.get("modes") or {}
    if "joint" not in modes or "independent" not in modes:
        return "<!-- no sensing benchmark data -->\n"
    ep = max(float(bench.get("config", {}).get("episodes", 1) or 1), 1.0)
    i, j = modes["independent"], modes["joint"]

    def row(label, a, b, places=3, arrow="lower is better"):
        fa = "--" if a is None or not math.isfinite(a) else f"{a:.{places}f}"
        fb = "--" if b is None or not math.isfinite(b) else f"{b:.{places}f}"
        return f"| {label} | {fa} | **{fb}** | {arrow} |"

    out = [
        "<!-- Generated by scripts/make_tables.py from "
        "results/sensing_benchmark.json. Do not edit. -->",
        "",
        "| | independent filters | joint filter (ours) | |",
        "|---|---|---|---|",
        row("Precision at p ≥ 0.5", i["prf@0.5"]["precision"],
            j["prf@0.5"]["precision"], 3, "higher is better"),
        row("Recall at p ≥ 0.5", i["prf@0.5"]["recall"],
            j["prf@0.5"]["recall"], 3, "higher is better"),
        row("F1", i["prf@0.5"]["f1"], j["prf@0.5"]["f1"], 3, "higher is better"),
        row("False detections per hour",
            i["prf@0.5"]["false_alarms_per_hour"] / ep,
            j["prf@0.5"]["false_alarms_per_hour"] / ep, 0, "lower is better"),
        row("Arms above 0.5 when one is occupied",
            i.get("arms_above@0.5"), j.get("arms_above@0.5"), 2, "1.0 is ideal"),
        row("Correct arm is the argmax", i.get("localisation_top1"),
            j.get("localisation_top1"), 3, "higher is better"),
        row("Expected calibration error", i.get("ece"), j.get("ece"), 3,
            "lower is better"),
        row("Brier score", i.get("brier"), j.get("brier"), 3, "lower is better"),
        row("Area under ROC", i.get("auc"), j.get("auc"), 3,
            "unchanged — it was never the ranking"),
        row("Median range error (m)", i.get("range_median_ae_m"),
            j.get("range_median_ae_m"), 1, "lower is better"),
        row("Arrival-time MAE (s)", i.get("eta_mae_s"), j.get("eta_mae_s"), 1,
            "lower is better"),
        "",
    ]
    return "\n".join(out) + "\n"


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--results", type=str, default=str(RESULTS_DIR))
    p.add_argument("--out", type=str, default=str(PAPER_TABLES))
    args = p.parse_args()

    ensure_dirs()
    results = Path(args.results)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    def load(name):
        path = results / name
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None

    written = []

    main_data = load("evaluation_balanced.json")
    if main_data:
        (out / "table_main.tex").write_text(table_main(main_data), encoding="utf-8")
        (out / "table_significance.tex").write_text(table_significance(main_data),
                                                    encoding="utf-8")
        written += ["table_main.tex", "table_significance.tex"]

    det = load("detector_metrics.json")
    if det:
        (out / "table_detector.tex").write_text(table_detector(det), encoding="utf-8")
        written.append("table_detector.tex")

    cost_check = load("cost_signal_check.json")
    if cost_check:
        (out / "table_cost_signal.tex").write_text(table_cost_signal(cost_check),
                                                   encoding="utf-8")
        written.append("table_cost_signal.tex")

    bench = load("sensing_benchmark.json")
    if bench:
        (out / "table_sensing.tex").write_text(table_sensing(bench), encoding="utf-8")
        written.append("table_sensing.tex")

    if main_data:
        (out / "table_ablation.tex").write_text(table_ablation(main_data),
                                                encoding="utf-8")
        (out / "table_ev_class.tex").write_text(table_ev_class(main_data),
                                                encoding="utf-8")
        written += ["table_ablation.tex", "table_ev_class.tex"]

    # The README quotes the same numbers as the paper, from the same file.
    if main_data:
        (RESULTS_DIR / "readme_results.md").write_text(
            readme_results(main_data), encoding="utf-8")
        written.append("../results/readme_results.md")
    if bench:
        (RESULTS_DIR / "readme_sensing.md").write_text(
            readme_sensing(bench), encoding="utf-8")
        written.append("../results/readme_sensing.md")

    robust = load("robustness.json")
    if robust:
        (out / "table_robustness.tex").write_text(table_robustness(robust),
                                                  encoding="utf-8")
        written.append("table_robustness.tex")

    lit = load("literature.json")
    if lit:
        (out / "table_literature.tex").write_text(table_literature(lit),
                                                  encoding="utf-8")
        written.append("table_literature.tex")

    sur = load("surrogate_validation.json")
    if sur:
        (out / "table_surrogate.tex").write_text(table_surrogate(sur), encoding="utf-8")
        written.append("table_surrogate.tex")

    by_regime = {}
    for regime in ("balanced", "asymmetric", "peak", "surge"):
        d = load(f"evaluation_{regime}.json")
        if d:
            by_regime[regime] = d["results"]
    if len(by_regime) > 1:
        (out / "table_regimes.tex").write_text(table_regimes(by_regime), encoding="utf-8")
        written.append("table_regimes.tex")

    # The paper \inputs a fixed set of tables. Any that have no data yet get a
    # stub, so main.tex compiles at every stage of the pipeline instead of only
    # at the end -- reviewing the structure should not require finishing the
    # experiments first.
    expected = ["table_main.tex", "table_significance.tex", "table_detector.tex",
                "table_surrogate.tex", "table_regimes.tex", "table_cost_signal.tex",
                "table_literature.tex", "table_calibration.tex",
                "table_sensing.tex", "table_ablation.tex", "table_ev_class.tex",
                "table_robustness.tex"]
    stubs = []
    for name in expected:
        path = out / name
        if not path.exists():
            path.write_text(
                f"% {name}: no results yet. Generated by scripts/make_tables.py\n"
                f"% once the corresponding experiment has been run.\n",
                encoding="utf-8")
            stubs.append(name)

    for name in written:
        print(f"  wrote {out / name}")
    if stubs:
        print(f"  stubbed (no data yet): {', '.join(stubs)}")
    if not written:
        print("no result files found; run the experiments first")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
