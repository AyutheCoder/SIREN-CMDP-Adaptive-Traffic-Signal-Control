def table_regimes(by_regime: dict) -> str:
    if len(by_regime) < 2:
        return "% only one demand regime evaluated\n"
    controllers = ["actuated", "max_pressure", "max_pressure_preempt", "siren_cmdp"]
    controllers = [c for c in controllers
                   if any(c in by_regime[r] for r in by_regime)]
    regimes = list(by_regime)
    lines = [
        r"% Auto-generated by scripts/make_tables.py -- do not edit.",
        r"\begin{table*}[tp]",
        r"\centering",
        r"\caption{Transfer to demand patterns never seen in training. The agent "
        r"was trained only on balanced demand; asymmetric, peak and surge are "
        r"held out. Each cell is background delay / emergency-vehicle stopped "
        r"delay, in seconds.}",
        r"\label{tab:regimes}",
        r"\small",
        r"\begin{tabular}{l" + "r" * len(regimes) + "}",
        r"\toprule",
        r"Controller & " + " & ".join(esc(r) for r in regimes) + r" \\",
        r"\midrule",
    ]
    for c in controllers:
        cells = []
        for r in regimes:
            agg = by_regime[r].get(c, {}).get("aggregate", {})
            bg = agg.get("mean_time_loss_s_mean")
            ev = agg.get("ev_mean_time_loss_s_mean")
            if bg is None or not np.isfinite(bg):
                cells.append("--")
            else:
                ev_s = f"{ev:.1f}" if ev is not None and np.isfinite(ev) else "--"
                cells.append(f"{bg:.1f} / {ev_s}")
        lines.append(f"{PRETTY.get(c, esc(c))} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(lines)


def table_literature(lit: dict) -> str:
    """Positioning against the published record.

    Deliberately not a leaderboard. Every reported figure in the last column is
    the authors' own headline on their own network, demand and simulator, so
    ranking them against each other -- or against ours -- would be meaningless.
    The columns that carry the argument are the first three: what the controller
    is assumed to know, whether it has any answer for simultaneous requests, and
    what holds in the worst case.
    """
    rows = lit.get("entries", [])
    if not rows:
        return "% no literature data\n"

    lines = [
        r"% Generated by scripts/make_tables.py -- do not edit.",
        r"\begin{table*}[tp]",
        r"\centering",
        r"\caption{Where this work sits. The reported-improvement column records "
        r"each paper's own headline number on its own network and simulator; the "
        r"entries are not measured on a common benchmark and are not comparable "
        r"with each other. The first three columns are the comparison that "
        r"matters: what the controller is assumed to know about the emergency "
        r"vehicle, whether simultaneous conflicting requests are handled at all, "
        r"and what is guaranteed regardless of what the sensor reports.}",
        r"\label{tab:literature}",
        r"\small",
        r"\begin{tabularx}{\textwidth}{@{}l X X X l@{}}",
        r"\toprule",
        r"Method & What it must be told & Simultaneous requests & Worst-case guarantee "
        r"& Reported \\",
        r"\midrule",
    ]
    for e in rows:
        label = esc(e.get("label", ""))
        if e.get("key") == "this_work":
            label = r"\textbf{" + label + "}"
        imp = e.get("reported_ev_improvement_pct")
        if imp is None:
            rep = r"---"
        else:
            rep = f"{imp:.1f}\\%"
        lines.append(
            f"{label} & {esc(e.get('sensing',''))} & {esc(e.get('conflicts',''))} & "
            f"{esc(e.get('guarantees',''))} & {rep} \\\\")
    lines += [r"\bottomrule", r"\end{tabularx}", r"\end{table*}", ""]
    return "\n".join(lines)


def table_sensing(bench: dict) -> str:
    """Joint versus independent presence filtering.

    Both filters see byte-identical detector output on identical seeds; the only
    difference is whether the four readings are explained jointly. Precision,
    calibration and localisation are reported together with recall, because the
    two filters move in opposite directions on recall and a table that omitted
    it would be choosing the operating point that flatters us.
    """
    modes = bench.get("modes") or {}
    order = [m for m in ("independent", "joint") if m in modes]
    if len(order) < 2:
        return "% no sensing benchmark data\n"

    def row(label, fn, places=3, better="lower"):
        vals = [fn(modes[m]) for m in order]
        cells = []
        for m, v in zip(order, vals):
            txt = "---" if v is None or not math.isfinite(float(v)) \
                else f"{float(v):.{places}f}"
            if m == "joint":
                txt = r"\textbf{" + txt + "}"
            cells.append(txt)
        arrow = r"$\downarrow$" if better == "lower" else r"$\uparrow$"
        return f"{label} {arrow} & " + " & ".join(cells) + r" \\"

    cfg = bench.get("config", {})
    lines = [
        r"% Generated by scripts/make_tables.py -- do not edit.",
        r"\begin{table*}[tp]",
        r"\centering",
        r"\caption{Presence estimation, scored against simulator ground truth over "
        f"{int(cfg.get('episodes', 0))} held-out hours at "
        f"{cfg.get('ev_rate_per_hour', 0):.0f} emergency vehicles per hour. "
        r"Both filters consume identical detector output on identical seeds. "
        r"Arrows give the direction of improvement. The independent filter is not "
        r"badly ranked --- the two areas under the ROC curve differ in the third "
        r"decimal --- it is badly localised and badly scaled, and a decision rule "
        r"consumes location and scale.}",
        r"\label{tab:sensing}",
        r"\small",
        r"\begin{tabular}{@{}lcc@{}}",
        r"\toprule",
        r" & Independent & Joint (ours) \\",
        r"\midrule",
        r"\multicolumn{3}{@{}l}{\emph{Detection}} \\",
        row("Precision at $p \\ge 0.5$", lambda d: d["prf@0.5"]["precision"],
            3, "higher"),
        row("Recall at $p \\ge 0.5$", lambda d: d["prf@0.5"]["recall"], 3, "higher"),
        row("$F_1$ at $p \\ge 0.5$", lambda d: d["prf@0.5"]["f1"], 3, "higher"),
        row("False detections per hour",
            lambda d: d["prf@0.5"]["false_alarms_per_hour"] / max(
                float(cfg.get("episodes", 1) or 1), 1.0), 0),
        row("Area under ROC", lambda d: d.get("auc"), 3, "higher"),
        r"\midrule",
        r"\multicolumn{3}{@{}l}{\emph{Localisation}} \\",
        row("Arms above $0.5$ when one is occupied (ideal 1)",
            lambda d: d.get("arms_above@0.5"), 2),
        row("Correct arm is the argmax", lambda d: d.get("localisation_top1"),
            3, "higher"),
        row("Median warning distance (m)",
            lambda d: d.get("warning_range_median_m@0.5"), 0, "higher"),
        row("Arrival detection rate",
            lambda d: d.get("arrival_detection_rate@0.5"), 3, "higher"),
        r"\midrule",
        r"\multicolumn{3}{@{}l}{\emph{Calibration and timing}} \\",
        row("Expected calibration error", lambda d: d.get("ece"), 3),
        row("Brier score", lambda d: d.get("brier"), 3),
        row("Arrival-time MAE (s)", lambda d: d.get("eta_mae_s"), 1),
        row("Median range error (m)", lambda d: d.get("range_median_ae_m"), 1),
        row("Class accuracy", lambda d: d.get("class_accuracy"), 3, "higher"),
        row("Cost per decision epoch (ms)",
            lambda d: d.get("median_epoch_us", float("nan")) / 1000.0, 1),
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table*}",
        "",
    ]
    return "\n".join(lines) + "\n"


def table_ablation(data: dict, full: str = "siren_arc") -> str:
    """One component removed at a time, everything else held fixed.

    Each row is the same trained policy and the same seeds; only the named
    component is disabled. Differences are therefore attributable rather than
    merely coincident, and both objectives are shown because a component can
    help one and hurt the other.
    """
    results = data.get("results", {})
    steps = [(full, "Full system"),
             ("arc_myopic", "act on sight (no just-in-time deadline)"),
             ("arc_indep", "independent per-approach filters"),
             ("arc_nocal", "raw posterior (no calibration)"),
             ("siren_priority", "no corridor (learned policy alone)")]
    steps = [(k, lbl) for k, lbl in steps if k in results]
    if len(steps) < 2:
        return "% no ablation data\n"

    base = results[full]["aggregate"]
    lines = [
        r"% Generated by scripts/make_tables.py -- do not edit.",
        r"\begin{table*}[tp]",
        r"\centering",
        r"\caption{Component ablation on identical seeded demand. Deltas are "
        r"against the full system; positive is worse. The two objectives are "
        r"shown separately because removing a component can help one and hurt "
        r"the other, and a single score would let that pass unnoticed.}",
        r"\label{tab:ablation}",
        r"\small",
        r"\begin{tabular}{@{}lcccc@{}}",
        r"\toprule",
        r" & \multicolumn{2}{c}{EV stopped (s)} & \multicolumn{2}{c}{Delay (s)} \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
        r"Configuration & value & $\Delta$ & value & $\Delta$ \\",
        r"\midrule",
    ]
    for key, label in steps:
        agg = results[key]["aggregate"]
        cells = []
        for metric in ("ev_mean_waiting_time_s", "mean_time_loss_s"):
            v = agg.get(f"{metric}_mean", float("nan"))
            b = base.get(f"{metric}_mean", float("nan"))
            cells.append("---" if not math.isfinite(v) else f"{v:.2f}")
            if key == full or not (math.isfinite(v) and math.isfinite(b)):
                cells.append("---")
            else:
                cells.append(f"{v - b:+.2f}")
        name = r"\textbf{" + esc(label) + "}" if key == full else esc(label)
        lines.append(f"{name} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(lines) + "\n"


def table_ev_class(data: dict, show=None) -> str:
    """Realised delay by emergency-vehicle class.

    The scheduler weights an ambulance above a fire appliance above a police car,
    from the acoustic class posterior alone. If that weighting does anything the
    realised delays come out in the same order; if it does not, the triage term
    is decoration. This table is what says which, and it is reported whichever
    way it comes out.
    """
    results = data.get("results", {})
    classes = [("ambulance", "Ambulance", 1.0),
               ("fire", "Fire appliance", 0.9),
               ("police", "Police", 0.7)]
    names = [n for n in (show or ["siren_arc", "max_pressure_preempt",
                                  "fixed_time"]) if n in results]
    if not names:
        return "% no per-class data\n"
    lines = [
        r"% Generated by scripts/make_tables.py -- do not edit.",
        r"\begin{table*}[tp]",
        r"\centering",
        r"\caption{Emergency stopped delay by vehicle class, with the triage "
        r"weight the scheduler assigns each class. The class is inferred from "
        r"the siren's timbre by the same detector that reports presence; no "
        r"vehicle announces itself. Ordering in the delays is the test of "
        r"whether the triage weight is doing anything.}",
        r"\label{tab:evclass}",
        r"\small",
        r"\begin{tabular}{@{}l" + "c" * len(names) + r"@{}}",
        r"\toprule",
        r"Class (triage weight) & " + " & ".join(
            esc(PRETTY.get(n, n)) for n in names) + r" \\",
        r"\midrule",
    ]
    for key, label, weight in classes:
        cells = []
        for n in names:
            agg = results[n]["aggregate"]
            v = agg.get(f"ev_{key}_mean_waiting_time_s_mean", float("nan"))
            ci = agg.get(f"ev_{key}_mean_waiting_time_s_ci95", float("nan"))
            if not math.isfinite(v):
                cells.append("---")
            elif math.isfinite(ci):
                cells.append(f"{v:.2f}\\,$\\pm$\\,{ci:.2f}")
            else:
                cells.append(f"{v:.2f}")
        lines.append(f"{esc(label)} ({weight:.1f}) & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(lines) + "\n"


def table_robustness(data: dict) -> str:
    """Graceful degradation under sensor loss.

    The comparison a transponder-based scheme cannot make: an infrared or V2I
    link has no partial failure mode, so there is no row between "works" and
    "does not". A passive acoustic front end has a whole column of them, and the
    question worth answering is whether the controller tracks the sensor down
    gently or falls off a cliff. The last row is the same policy with the
    microphones removed entirely, which is where any degradation is heading.
    """
    results = data.get("results") or {}
    order = [k for k in ("nominal", "noise+5", "noise+10", "noise+15",
                         "mic1", "mic2", "deaf") if k in results]
    if len(order) < 2:
        return "% no robustness data\n"
    label = {"nominal": "Nominal", "noise+5": "Ambient floor $+5$\,dB",
             "noise+10": "Ambient floor $+10$\,dB",
             "noise+15": "Ambient floor $+15$\,dB",
             "mic1": "One mast failed", "mic2": "Two masts failed",
             "deaf": "No acoustic sensing at all"}
    lines = [
        r"% Generated by scripts/make_tables.py -- do not edit.",
        r"\begin{table*}[tp]",
        r"\centering",
        r"\caption{Degradation under sensor loss, on seeds held out from every "
        r"other result. A failed mast is silent rather than noisy, and the "
        r"filter is told which masts are out, so its likelihood marginalises "
        r"over the missing observation instead of reading silence as evidence "
        r"of absence.}",
        r"\label{tab:robustness}",
        r"\small",
        r"\begin{tabular}{@{}lcccc@{}}",
        r"\toprule",
        r"Condition & EV stopped (s) & clean pass & delay (s) & jam \\",
        r"\midrule",
    ]
    for key in order:
        agg = results[key]["aggregate"]
        if key == "deaf":
            lines.append(r"\midrule")
        name = label.get(key, key)
        if key == "nominal":
            name = r"\textbf{" + name + "}"
        lines.append(
            f"{name} & {fmt(agg, 'ev_mean_waiting_time_s')} & "
            f"{fmt(agg, 'ev_zero_stop_rate', 3)} & "
            f"{fmt(agg, 'mean_time_loss_s')} & {fmt_jam(agg)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(lines) + "\n"


