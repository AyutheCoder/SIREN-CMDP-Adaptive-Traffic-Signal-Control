def table_surrogate(data: dict) -> str:
    sensor = data.get("sensor_level", {})
    comparison = data.get("comparison", {})
    lines = [
        r"% Auto-generated by scripts/make_tables.py -- do not edit.",
        r"\begin{table*}[tp]",
        r"\centering",
        r"\caption{Fidelity of the fitted surrogate sensor used inside the RL "
        r"loop, against the full audio-plus-CNN pipeline. Sensor-level figures "
        rf"are over {sensor.get('n_scenes', 0)} matched scenes; system-level "
        r"differences are paired bootstraps over complete control episodes on "
        r"identical seeds. Large $p$-values are the desired outcome here: they "
        r"indicate the substitution is not detectable in the reported metrics.}",
        r"\label{tab:surrogate}",
        r"\small",
        r"\begin{tabular}{lrr}",
        r"\toprule",
        r"Quantity & End-to-end CNN & Surrogate \\",
        r"\midrule",
    ]

    def pair(label, k1, k2, places=3):
        a, b = sensor.get(k1), sensor.get(k2)
        f = lambda v: f"{v:.{places}f}" if isinstance(v, (int, float)) and np.isfinite(v) else "--"
        lines.append(f"{label} & {f(a)} & {f(b)} \\\\")

    pair("Detection rate", "detection_rate_e2e", "detection_rate_surrogate")
    pair("False-positive rate", "false_positive_rate_e2e", "false_positive_rate_surrogate")
    pair("Range MAPE", "range_mape_e2e", "range_mape_sur")
    gap = sensor.get("max_detection_rate_gap")
    if isinstance(gap, (int, float)) and np.isfinite(gap):
        lines.append(r"\midrule")
        lines.append(rf"Largest detection-rate gap across SNR bins & \multicolumn{{2}}{{r}}{{{gap:.3f}}} \\")

    if comparison:
        lines.append(r"\midrule")
        lines.append(r"\multicolumn{3}{l}{\emph{Closed-loop difference (surrogate $-$ CNN)}} \\")
        labels = {
            "mean_time_loss_s": "Background delay (s)",
            "ev_mean_time_loss_s": "Emergency-vehicle delay (s)",
            "mean_queue": "Mean queue (veh)",
        }
        for key, label in labels.items():
            stat = comparison.get(key)
            if not stat:
                continue
            lines.append(
                rf"{label} & \multicolumn{{2}}{{r}}{{{stat['diff']:+.3f} "
                rf"($p={stat['p_value']:.3f}$)}} \\"
            )
    speed = data.get("speedup")
    if isinstance(speed, (int, float)) and np.isfinite(speed):
        lines.append(r"\midrule")
        lines.append(rf"Wall-clock speedup & \multicolumn{{2}}{{r}}{{{speed:.1f}$\times$}} \\")

    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(lines)


