def table_significance(data: dict) -> str:
    tests = data.get("significance") or {}
    if not tests:
        return "% no significance tests available\n"
    lines = [
        r"% Auto-generated by scripts/make_tables.py -- do not edit.",
        r"\begin{table*}[tp]",
        r"\centering",
        r"\caption{Paired bootstrap against the max-pressure baseline "
        r"(20{,}000 resamples). Runs are paired by seed, so scenario variance "
        r"is removed. Negative differences favour the listed controller.}",
        r"\label{tab:significance}",
        r"\small",
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        r" & \multicolumn{2}{c}{Background delay} & \multicolumn{2}{c}{EV stopped delay} \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
        r"Controller & $\Delta$ (s) & $p$ & $\Delta$ (s) & $p$ \\",
        r"\midrule",
    ]
    for name, entry in tests.items():
        bg = entry.get("mean_time_loss_s", {})
        ev = entry.get("ev_mean_waiting_time_s", {})
        def cell(d, key, places=2):
            v = d.get(key)
            return f"{v:.{places}f}" if v is not None and np.isfinite(v) else "--"
        lines.append(
            f"{PRETTY.get(name, esc(name))} & "
            f"{cell(bg, 'diff')} & {cell(bg, 'p_value', 4)} & "
            f"{cell(ev, 'diff')} & {cell(ev, 'p_value', 4)} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(lines)


