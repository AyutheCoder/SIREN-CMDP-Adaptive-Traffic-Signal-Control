"""Splice the generated result tables into README.md.

The paper's tables are a pure function of ``results/*.json`` and always have
been: ``make_tables.py`` writes them and ``main.tex`` ``\\input``s them, so a
re-run cannot leave a stale number behind. The README quoted the same numbers
but was updated by hand, which is exactly the gap through which a stale table
survives a re-run -- and a README table that disagrees with the paper it
summarises is worse than no table.

This closes it. ``make_tables.py`` already emits Markdown renderings of the two
tables the README carries (``results/readme_results.md`` and
``results/readme_sensing.md``); this script drops them into place, matching on
the generated-by comment that heads each block and replacing everything up to
the blank line that ends the table.

    python scripts/update_readme.py            # rewrite README.md in place
    python scripts/update_readme.py --check    # fail if it would change (CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from atsc.config import REPO_ROOT, RESULTS_DIR

BLOCKS = (
    ("results/evaluation_balanced.json", "readme_results.md"),
    ("results/sensing_benchmark.json", "readme_sensing.md"),
)


def marker(source: str) -> str:
    return f"<!-- Generated by scripts/make_tables.py from {source}. Do not edit. -->"


def splice(readme: str, source: str, block: str) -> str:
    """Replace the generated block headed by ``marker(source)``."""
    head = marker(source)
    start = readme.find(head)
    if start < 0:
        raise SystemExit(
            f"README has no block for {source}; expected the line:\n  {head}")
    # The block runs to the first blank line after the table body. Matching on
    # the table rather than on a closing marker keeps the README readable as
    # Markdown, which a fenced region would not.
    cursor = start + len(head)
    while cursor < len(readme):
        end = readme.find("\n\n", cursor)
        if end < 0:
            end = len(readme)
            break
        # A table row directly after the gap means the blank line was inside
        # the block, which happens when a generator separates sections.
        if not readme[end + 2: end + 3] == "|":
            break
        cursor = end + 2
    return readme[:start] + block.strip() + readme[end:]


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--readme", default=str(REPO_ROOT / "README.md"))
    p.add_argument("--results", default=str(RESULTS_DIR))
    p.add_argument("--check", action="store_true",
                   help="exit non-zero if the README is out of date rather "
                        "than rewriting it")
    args = p.parse_args()

    readme_path = Path(args.readme)
    original = readme_path.read_text(encoding="utf-8")
    updated = original
    used = []

    for source, generated in BLOCKS:
        path = Path(args.results) / generated
        if not path.exists():
            print(f"skip {generated}: not generated yet (run make_tables.py)")
            continue
        updated = splice(updated, source, path.read_text(encoding="utf-8"))
        used.append(generated)

    if updated == original:
        print(f"README.md is up to date ({', '.join(used) or 'nothing to splice'})")
        return 0
    if args.check:
        print("README.md is stale: run scripts/update_readme.py")
        return 1
    readme_path.write_text(updated, encoding="utf-8")
    print(f"README.md updated from {', '.join(used)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
