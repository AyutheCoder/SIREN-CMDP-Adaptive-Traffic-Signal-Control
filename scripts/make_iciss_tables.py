"""The quantitative tables in the ICISS paper, generated from ``results/``.

    python scripts/make_iciss_tables.py

Writes LaTeX fragments into ``paper_iciss/tables``. Only the tables whose cells
are *measurements* live here; the related-work and simulation-parameter tables
are hand-authored in the paper source, because their cells are statements about
other people's papers and about our configuration, not numbers this code
produced.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
RESULTS = REPO / "results"
OUT = REPO / "paper_iciss" / "tables"
OUT.mkdir(parents=True, exist_ok=True)

from atsc.evaluation.metrics import paired_bootstrap_pvalue  # noqa: E402

EVAL = json.loads((RESULTS / "evaluation_balanced.json").read_text())
CFG, RES = EVAL["config"], EVAL["results"]
NB = 20000          # bootstrap resamples, matching the evaluation harness


def runs(c):
    return sorted(RES[c]["runs"], key=lambda r: r["seed"])


def series(c, k):
    return np.array([r[k] for r in runs(c)], dtype=float)


def med(c, k):
    return float(np.median(series(c, k)))


def jam(c):
    return int(RES[c]["aggregate"]["n_jammed"])


def stars(p):
    return "$^{**}$" if p < 0.01 else ("$^{*}$" if p < 0.05 else "")


def write(name, body):
    (OUT / name).write_text(body, encoding="utf-8")
    print(f"  wrote {name}")


# ==================================================== main comparison table
def table_main():
    cols = ["fixed_time", "actuated", "max_pressure", "max_pressure_preempt",
            "base_arc", "siren_arc"]
    head = ["Fixed", "Actu.", "MaxP", "MaxP+P", "RL", "\\textbf{Ours}"]
    OURS, REF_A, REF_B = "siren_arc", "max_pressure_preempt", "base_arc"

    # (key, label, unit, format, +1 if higher is better)
    rows = [
        ("mean_waiting_time_s", "Mean waiting time", "s", "{:.2f}", -1),
        ("mean_time_loss_s", "Mean delay (time loss)", "s", "{:.2f}", -1),
        ("p95_time_loss_s", "95th percentile delay", "s", "{:.2f}", -1),
        ("mean_queue", "Mean queue length", "veh", "{:.2f}", -1),
        ("mean_stops", "Stops per vehicle", "", "{:.2f}", -1),
        ("throughput", "Throughput", "veh/h", "{:.0f}", +1),
        ("jain_fairness", "Jain fairness (approaches)", "", "{:.3f}", +1),
        ("co2_g_per_vehicle", "CO$_2$ per vehicle", "g", "{:.1f}", -1),
        (None, None, None, None, None),          # rule
        ("ev_mean_waiting_time_s", "EV stopped delay", "s", "{:.2f}", -1),
        ("ev_p95_waiting_time_s", "EV stopped delay, 95th pct.", "s", "{:.2f}", -1),
        ("ev_max_waiting_time_s", "EV worst single wait", "s", "{:.0f}", -1),
        ("ev_mean_stops", "EV stops per vehicle", "", "{:.2f}", -1),
        ("ev_zero_stop_rate", "EV clean-pass rate", "", "{:.3f}", +1),
        ("ev_mean_time_loss_s", "EV time loss", "s", "{:.2f}", -1),
        (None, None, None, None, None),
        ("max_movement_wait_s", "Worst movement wait", "s", "{:.0f}", -1),
    ]

    out = []
    for key, label, unit, fmt, sgn in rows:
        if key is None:
            out.append("\\midrule")
            continue
        vals = {c: med(c, key) for c in cols}
        best = (max if sgn > 0 else min)(vals.values())
        cells = []
        for c in cols:
            txt = fmt.format(vals[c])
            if abs(vals[c] - best) < 1e-9:
                txt = f"\\textbf{{{txt}}}"
            cells.append(txt)
        gains = []
        for ref in (REF_A, REF_B):
            a, b = vals[OURS], vals[ref]
            if abs(b) < 1e-12:
                gains.append("---"); continue
            imp = (b - a) / abs(b) * 100.0 * (-1 if sgn > 0 else 1)
            p = paired_bootstrap_pvalue(series(OURS, key), series(ref, key),
                                        n_boot=NB)["p_value"]
            if abs(imp) < 0.05:
                gains.append("tie")
            elif imp > 0:
                gains.append(f"$+${imp:.1f}\\%{stars(p)}")
            else:
                gains.append(f"\\textcolor{{gray}}{{$-${abs(imp):.1f}\\%{stars(p)}}}")
        out.append(f"{label} & {unit} & " + " & ".join(cells) + " & "
                   + " & ".join(gains) + " \\\\")

    jams = [f"{jam(c)}" for c in cols]
    out.append("\\midrule")
    out.append("Gridlocked seeds & /12 & " + " & ".join(jams)
               + " & tie & tie \\\\")

    body = r"""% Generated by scripts/make_iciss_tables.py -- do not edit.
\begin{table}[!htbp]
\centering
\caption{Multi-parameter comparison. Every controller was measured by us under one
protocol --- @NSEED@ seeds $\times$ @HOR@\,s, @FLOW@\,veh/h per approach, @EVR@
emergency vehicles/h, identical demand --- so the columns are comparable. Cells
are medians over seeds, best in bold. The last two columns give the change against
two \emph{named} references, not a per-row winner: MaxP+P is the strongest
emergency baseline, RL the same learned policy without the priority layer.
Positive means ours is better; where worse, the figure is grey rather than
omitted. Significance: paired bootstrap, $^{*}p<0.05$, $^{**}p<0.01$.}
\label{tab:params}
\scriptsize
% Ten columns on a 122mm measure: at 3pt of padding the table overruns it.
\setlength{\tabcolsep}{1.7pt}
\renewcommand{\arraystretch}{0.94}
\begin{tabular}{@{}llcccccc|cc@{}}
\toprule
& & \multicolumn{6}{c}{Median over seeds} & \multicolumn{2}{c}{Ours vs.} \\
\cmidrule(lr){3-8}\cmidrule(lr){9-10}
Parameter & Unit & @HEAD@ & MaxP+P & RL \\
\midrule
@ROWS@
\bottomrule
\end{tabular}
\\[2pt]
% The max-pressure caveat that used to sit here is made in the running text, so
% repeating it under the table costs five lines and says nothing new.
{\footnotesize Fixed = Webster fixed-time; Actu.\ = SUMO actuated; MaxP =
max-pressure; MaxP+P = max-pressure with Opticom-style hard preemption; RL = our
learned policy with the priority layer removed.}
\end{table}
"""
    body = (body.replace("@NSEED@", str(len(CFG["seeds"])))
                .replace("@HOR@", str(CFG["horizon"]))
                .replace("@FLOW@", f'{CFG["flow"]:g}')
                .replace("@EVR@", f'{CFG["ev_rate"]:g}')
                .replace("@HEAD@", " & ".join(head))
                .replace("@ROWS@", "\n".join(out)))
    write("tab_params.tex", body)


